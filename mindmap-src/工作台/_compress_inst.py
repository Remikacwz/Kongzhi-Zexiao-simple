FORBID = ['**', '`', '#']
ABS = ['保证', '一定', '必然']

def check_new(key, path, items):
    ok = True
    for s in items:
        if len(s) > 45:
            print(f'  !! {key} {path} len={len(s)} >45: {s}'); ok = False
        for f in FORBID:
            if f in s:
                print(f'  !! {key} {path} 含禁止标记 {f!r}: {s}'); ok = False
        for a in ABS:
            if a in s:
                print(f'  !! {key} {path} 含绝对化词 {a}: {s}'); ok = False
    return ok

allok = True
for key, reps in REPL.items():
    d = json.load(open(os.path.join(V6, key+'.json'), encoding='utf-8'))
    for (bi, ci, field, idx, items) in reps:
        arr = d['板块'][bi]['考点'][ci]['本卷实例'][field]
        old = arr[idx]
        if len(old) <= 45:
            print(f'  ?? {key} 板块{bi}考点{ci} {field}[{idx}] 原长{len(old)} 不超长，拒绝改'); allok=False; continue
        path = f'板块[{bi}]/{d["板块"][bi]["考点"][ci]["ref"]}/{field}[{idx}]'
        if not check_new(key, path, items):
            allok = False
    # also ensure no duplicate target paths overlap issues
