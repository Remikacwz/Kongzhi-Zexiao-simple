ANSWER = re.compile(r"答案是|答案为|解得\s*[A-Za-z_]?\s*=|所以\s*[A-Za-z_]+\s*=\s*[\d\-]|最终结果|因此\s*[A-Za-z_]+\s*=\s*[\d\-]|正确答案")
ABS = re.compile(r"一定|必然|绝对(?!值)|肯定|必定|毫无疑问")
MD = [(r"\*\*[^*]+\*\*","粗体"),(r"(?<![\d\w])#{1,4}\s+\S","标题"),(r"`[^`]+`","反引号")]

def validate():
    bad=0
    for key, entries in PLAN.items():
        for (blk,ref,field,idx), reps in entries.items():
            for s in reps:
                flags=[]
                if len(s)>45: flags.append("LEN=%d"%len(s))
                if ANSWER.search(s): flags.append("ANSWER"+ANSWER.search(s).group())
                if ABS.search(s): flags.append("ABS")
                for p,w in MD:
                    if re.search(p,s): flags.append("MD:"+w)
                if flags:
                    bad+=1
                    print("BAD", key, blk, ref, field, idx, flags, "|", s)
    print("validate done, bad=%d, entries=%d, total new items=%d" % (
        bad, sum(len(v) for v in PLAN.values()), sum(len(r) for v in PLAN.values() for r in v.values())))
    return bad

def apply():
    for key, entries in PLAN.items():
        p="思维导图_v6/"+key+".json"
        shutil.copy2(p,"_工作台/_bak_压缩_"+key+".json")
        d=json.load(open(p,encoding="utf-8"))
        for (blk,ref,field,idx), reps in entries.items():
            b=next((b for b in d["板块"] if b.get("名称")==blk), None)
            assert b, (key,blk)
            cands=[c for c in b["考点"] if c["ref"]==ref]
            assert len(cands)==1, (key,blk,ref,len(cands))
            lst=cands[0]["本卷实例"][field]
            assert idx < len(lst), (key,blk,ref,field,idx,len(lst))
            assert len(lst[idx])>45, (key,blk,ref,field,idx,len(lst[idx]),lst[idx])
            lst[idx:idx+1]=list(reps)
        json.dump(d, open(p,"w",encoding="utf-8"), ensure_ascii=False, indent=2)
        open(p,"a",encoding="utf-8").write("\n")
        print("applied", key, len(entries), "items")

if __name__=="__main__":
    if sys.argv[1]=="validate": sys.exit(1 if validate() else 0)
    elif sys.argv[1]=="apply": apply()
