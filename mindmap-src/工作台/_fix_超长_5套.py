def main():
    total = 0
    for key, fixes in FIX.items():
        src = r"思维导图_v6/%s.json" % key
        bak = r"_工作台/_bak_压缩_%s.json" % key
        shutil.copyfile(src, bak)
        d = json.load(open(src, encoding="utf-8"))
        for (bi, ci, field, ii, old, new) in fixes:
            arr = d["板块"][bi]["考点"][ci]["本卷实例"][field]
            got = arr[ii]
            assert got == old, "OLD MISMATCH %s [%d][%d].%s[%d]\n got=%r\n exp=%r" % (key,bi,ci,field,ii,got,old)
            assert len(old) > 45, "not long"
            bad = [(s,len(s)) for s in new if len(s)>45]
            assert not bad, "NEW TOO LONG %s: %r" % (key,bad)
            assert len(new) >= 2, "need split"
            arr[ii] = new[0]
            for extra in new[1:]:
                arr.append(extra)
            total += 1
        json.dump(d, open(src,"w",encoding="utf-8"), ensure_ascii=False, indent=2)
        # 末尾保持单个换行
        txt = open(src, encoding="utf-8").read()
        if not txt.endswith("\n"):
            open(src,"a",encoding="utf-8").write("\n")
        print("OK", key, "fixes=", len(fixes))
    print("TOTAL fixes =", total)

if __name__ == "__main__":
    main()
